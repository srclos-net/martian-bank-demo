#!/usr/bin/env python3
"""Regenerate deploy/manifests/infraops-scan.yaml from deploy/infraops/*.

deploy/manifests is a plain-directory Argo CD source (no kustomize), so the
scan script ships as a literal ConfigMap. Edit scan.py / capacity-profile.json,
then run:  python3 deploy/infraops/gen-manifest.py   (CI checks it's in sync)
"""
import os, sys
here = os.path.dirname(os.path.abspath(__file__))
out = os.path.join(here, "..", "manifests", "infraops-scan.yaml")

def block(path):
    return "\n".join(("    " + l) if l else "" for l in open(os.path.join(here, path)).read().rstrip("\n").split("\n"))

doc = f"""# GENERATED by deploy/infraops/gen-manifest.py — do not edit by hand.
# StackGen InfraOps scan for the re:Invent booth demo (docs/reinvent/):
# live-vs-Git drift + capacity policy + reconcile PR. Runs on demand:
#   kubectl -n martian-bank create job --from=cronjob/infraops-scan infraops-scan-$(date +%s)
# (deploy/booth/booth infraops does exactly that). The CronJob stays suspended.
# GitHub token: Secret infraops-github (key `token`), created out of band,
# fine-grained PAT scoped to srclos-net/martian-bank-demo (contents + pull
# requests: write). Without it the scan reports but opens no PR.
apiVersion: v1
kind: ServiceAccount
metadata:
  name: infraops-scan
  labels: {{app.kubernetes.io/part-of: martian-bank, app.kubernetes.io/name: infraops-scan}}
---
apiVersion: rbac.authorization.k8s.io/v1
kind: Role
metadata:
  name: infraops-scan
  labels: {{app.kubernetes.io/part-of: martian-bank, app.kubernetes.io/name: infraops-scan}}
rules:
  - apiGroups: ["apps"]
    resources: ["deployments"]
    verbs: ["get", "list"]
  - apiGroups: [""]
    resources: ["configmaps"]
    verbs: ["create"]
  - apiGroups: [""]
    resources: ["configmaps"]
    resourceNames: ["infraops-report"]
    verbs: ["get", "patch", "update"]
---
apiVersion: rbac.authorization.k8s.io/v1
kind: RoleBinding
metadata:
  name: infraops-scan
  labels: {{app.kubernetes.io/part-of: martian-bank, app.kubernetes.io/name: infraops-scan}}
roleRef: {{apiGroup: rbac.authorization.k8s.io, kind: Role, name: infraops-scan}}
subjects:
  - {{kind: ServiceAccount, name: infraops-scan}}
---
apiVersion: v1
kind: ConfigMap
metadata:
  name: infraops-scan
  labels: {{app.kubernetes.io/part-of: martian-bank, app.kubernetes.io/name: infraops-scan}}
data:
  scan.py: |
{block("scan.py")}
  capacity-profile.json: |
{block("capacity-profile.json")}
---
apiVersion: batch/v1
kind: CronJob
metadata:
  name: infraops-scan
  labels: {{app.kubernetes.io/part-of: martian-bank, app.kubernetes.io/name: infraops-scan}}
spec:
  schedule: "0 0 1 1 *"
  suspend: true          # on demand only (see header)
  concurrencyPolicy: Forbid
  successfulJobsHistoryLimit: 3
  failedJobsHistoryLimit: 3
  jobTemplate:
    spec:
      backoffLimit: 0
      ttlSecondsAfterFinished: 3600
      template:
        metadata:
          labels: {{app.kubernetes.io/name: infraops-scan}}
        spec:
          serviceAccountName: infraops-scan
          restartPolicy: Never
          securityContext: {{runAsNonRoot: true, runAsUser: 65534, runAsGroup: 65534}}
          volumes:
            - {{name: scripts, configMap: {{name: infraops-scan}}}}
            - {{name: work, emptyDir: {{}}}}
            - {{name: tools, emptyDir: {{}}}}
          initContainers:
            - name: conftest
              image: openpolicyagent/conftest:v0.56.0
              command: ["cp", "/conftest", "/tools/conftest"]
              volumeMounts: [{{name: tools, mountPath: /tools}}]
              resources:
                requests: {{cpu: 10m, memory: 16Mi}}
                limits: {{cpu: 250m, memory: 64Mi}}
          containers:
            - name: scan
              image: alpine/k8s:1.31.4
              command: ["python3", "/scripts/scan.py"]
              env:
                - {{name: MODE, value: scan-pr}}
                - {{name: PATH, value: "/tools:/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin"}}
                - {{name: HOME, value: /work}}
                - {{name: HELM_CACHE_HOME, value: /work/.helm/cache}}
                - {{name: HELM_CONFIG_HOME, value: /work/.helm/config}}
                - {{name: HELM_DATA_HOME, value: /work/.helm/data}}
                - name: GITHUB_TOKEN
                  valueFrom: {{secretKeyRef: {{name: infraops-github, key: token, optional: true}}}}
              volumeMounts:
                - {{name: scripts, mountPath: /scripts}}
                - {{name: work, mountPath: /work}}
                - {{name: tools, mountPath: /tools}}
              resources:
                requests: {{cpu: 50m, memory: 128Mi}}
                limits: {{cpu: "1", memory: 512Mi}}
"""
if len(sys.argv) > 1 and sys.argv[1] == "--check":
    sys.exit(0 if open(out).read() == doc else "deploy/manifests/infraops-scan.yaml is stale: run deploy/infraops/gen-manifest.py")
open(out, "w").write(doc)
print("wrote", os.path.relpath(out))
